/** Поиск эмодзи по словам (без учёта регистра, ё = е). */
export function searchEmoji(query: string, limit = 64): string[] {
  const q = query.trim().toLowerCase().replace(/ё/g, 'е');
  if (!q) return [];
  const out: string[] = [];
  const seen = new Set<string>();
  const push = (e: string) => {
    if (!seen.has(e) && out.length < limit) {
      seen.add(e);
      out.push(e);
    }
  };
  for (const [e, words] of Object.entries(EMOJI_KEYWORDS)) {
    if (words.replace(/ё/g, 'е').split(' ').some((w) => w.startsWith(q))) push(e);
  }
  for (const c of EMOJI_CATEGORIES) {
    if (CATEGORY_WORDS[c.key]?.split(' ').some((w) => w.startsWith(q))) c.emojis.slice(0, 40).forEach(push);
  }
  return out;
}

/** Удалить последний символ с учётом составных эмодзи (флаги, ZWJ, оттенки кожи). */
export function deleteLastSymbol(text: string): string {
  if (!text) return text;
  try {
    const m = text.match(/(?:\p{Regional_Indicator}{2}|\p{Extended_Pictographic}(?:\uFE0F|\p{Emoji_Modifier})?(?:\u200D\p{Extended_Pictographic}(?:\uFE0F|\p{Emoji_Modifier})?)*|[0-9#*]\uFE0F?\u20E3)$/u);
    if (m) return text.slice(0, text.length - m[0].length);
  } catch {
    // движок без \p{...} — ниже простой вариант
  }
  const chars = Array.from(text);
  chars.pop();
  return chars.join('');
}
